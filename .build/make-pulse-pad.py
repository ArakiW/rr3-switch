# Make a pad script that PULSES the confirm button.
#
# WHY.  MEASURED 2026-11-09 (rounds m2 and m3, both Nov-4 and Nov-9 builds):
# the guest froze on a modal "you received 50 gold" popup -- the panel with
# the coin icon, the empty text area and the red glove parked at its top
# right corner -- and never reached the race.  The archived frame is
# 20261109-155529-eden-rr3-m3-nov4-census-off/frames/frame-005200.png.
#
# The popup is PERSISTED by the guest, so it survives between rounds: once
# it is on screen, every later round starts stuck on it.
#
# WHY A HELD BUTTON CANNOT DISMISS IT: the autopilot pad script is a state
# timeline, and the line "[at 600] ... b=0x001" holds the guest's BTN_A down
# from frame 600 to the end of the round.  There is never a release, so the
# guest's UI never sees a BUTTON-DOWN TRANSITION after the popup appears.
# A modal dialog that waits for a press waits forever.
#
# THE TENSION, AND WHY THE PULSE SOLVES IT: the guest's accelerator is
# BTN_A (MEASURED 2026-10-24, archive 20261024-134104-eden-thr-btnA: with
# button 0 held the car accelerates; with R2 alone the guest draws its own
# "hold the brake to reverse" message and the car does NOT move).  So the
# button cannot simply be released.  It is PULSED instead: held for most of
# the time, released for a few frames every cycle, which gives the guest a
# fresh press edge every cycle while the car keeps accelerating.
#
# Usage:  python .build/make-pulse-pad.py [out-path] [--on N] [--off N] [--from N]
import sys
from pathlib import Path

DEFAULT_OUT = Path(r"E:\AI\RealRacing3-switch\native-switch\card\rr3-pad-autopilot-pulse.txt")

HEADER = """# The confirm-then-throttle script, WITH A PULSE ON THE CONFIRM BUTTON.
#
# This is the autopilot pad script with ONE change: the guest's BTN_A is
# released for a few frames every cycle instead of being held down for the
# whole round.
#
# WHY IT EXISTS.  MEASURED 2026-11-09 (rounds m2 and m3): the guest froze
# on a modal "you received 50 gold" popup and never reached the race, and
# the popup is persisted by the guest so it survives between rounds.  A
# HELD button never produces a button-down TRANSITION, and a modal dialog
# that waits for a press waits forever.
#
# BTN_A is also the guest's accelerator (MEASURED 2026-10-24, archive
# 20261024-134104-eden-thr-btnA), so the button cannot simply be released.
# It is pulsed: held for most of the cycle, released for a few frames, so
# the guest gets a fresh press every cycle and the car still accelerates.
#
# Generated by .build/make-pulse-pad.py -- do not hand-edit.
#
# The script is a state timeline: the last line whose "at" frame is at or
# before the current frame applies.
"""


def main() -> int:
    args = sys.argv[1:]
    out = DEFAULT_OUT
    on = 20
    off = 4
    first = 600
    while args:
        a = args.pop(0)
        if a == "--on":
            on = int(args.pop(0))
        elif a == "--off":
            off = int(args.pop(0))
        elif a == "--from":
            first = int(args.pop(0))
        else:
            out = Path(a)

    lines = [HEADER]
    lines.append("[at 0] lx=0 ly=0 rx=0 ry=0 lt=0 rt=0 b=0x000")
    lines.append("[at {0}] lx=0 ly=0 rx=0 ry=0 lt=0 rt=0 b=0x001".format(first))

    # The throttle, as in the original script: it comes on a little after the
    # confirm, and it stays on for the rest of the race.
    throttle_at = first + 350
    frame = first
    cycle = on + off
    while frame < throttle_at:
        frame += cycle
        if frame < throttle_at:
            lines.append("[at {0}] b=0x000".format(frame))       # the gap
            frame += off
            if frame < throttle_at:
                lines.append("[at {0}] b=0x001".format(frame))   # pressed again
    lines.append("[at {0}] lx=0 ly=0 rx=0 ry=0 lt=0 rt=1.0 b=0x001".format(throttle_at))

    # And the pulse continues, so a popup that appears DURING the race is
    # dismissed too.
    frame = throttle_at
    while frame < 40000:
        frame += cycle
        lines.append("[at {0}] b=0x000".format(frame))
        frame += off
        lines.append("[at {0}] b=0x001".format(frame))

    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("wrote {0} ({1} lines, pulse {2} on / {3} off, from frame {4})".format(
        out, len(lines), on, off, first))
    return 0


if __name__ == "__main__":
    sys.exit(main())
