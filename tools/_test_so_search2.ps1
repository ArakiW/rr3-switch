# Faster SO string search using .NET
$ErrorActionPreference = 'Stop'

# Read the SO
$so = [System.IO.File]::ReadAllBytes('E:\AI\RealRacing3-switch\reverse\native\arm64\libRealRacing3.so')
Write-Output "SO size: $($so.Length) bytes"

# Quick scan for specific byte patterns (file signatures or strings)
$patterns = @{
    'MT_GL' = @(0x4D, 0x54, 0x5F, 0x47, 0x4C)
    'rr3' = @(0x72, 0x72, 0x33)
    'csdk' = @(0x63, 0x73, 0x64, 0x6B)
    'Firemon' = @(0x46, 0x69, 0x72, 0x65, 0x6D, 0x6F, 0x6E)
    'RealRac' = @(0x52, 0x65, 0x61, 0x6C, 0x52, 0x61, 0x63)
    'vsh' = @(0x76, 0x73, 0x68)
    'fsh' = @(0x66, 0x73, 0x68)
    'gui' = @(0x2E, 0x67, 0x75, 0x69)  # .gui
    '.vsh' = @(0x2E, 0x76, 0x73, 0x68)
    '.fsh' = @(0x2E, 0x66, 0x73, 0x68)
    '.xsh' = @(0x2E, 0x78, 0x73, 0x68)
    'depot' = @(0x64, 0x65, 0x70, 0x6F, 0x74)
    'asset_' = @(0x61, 0x73, 0x73, 0x65, 0x74, 0x5F)
    'asset/' = @(0x61, 0x73, 0x73, 0x65, 0x74, 0x2F)
    'Shaders' = @(0x53, 0x68, 0x61, 0x64, 0x65, 0x72, 0x73)
    'Shader' = @(0x53, 0x68, 0x61, 0x64, 0x65, 0x72)
    'feats' = @(0x66, 0x65, 0x61, 0x74, 0x73)
    'mtShader' = @(0x6D, 0x74, 0x53, 0x68, 0x61, 0x64, 0x65, 0x72)
    'decrypt' = @(0x64, 0x65, 0x63, 0x72, 0x79, 0x70, 0x74)
    'cipher' = @(0x63, 0x69, 0x70, 0x68, 0x65, 0x72)
    'obfusc' = @(0x6F, 0x62, 0x66, 0x75, 0x73, 0x63)
    'AES' = @(0x41, 0x45, 0x53)
    'RC4' = @(0x52, 0x43, 0x34)
    'GLSLES' = @(0x47, 0x4C, 0x5F, 0x47, 0x4C, 0x45, 0x53)
    'GLES3' = @(0x47, 0x4C, 0x45, 0x53, 0x33)
}

Write-Output "`n=== Searching for byte patterns in SO ==="
foreach ($name in $patterns.Keys) {
    $bytes = $patterns[$name]
    $hits = New-Object System.Collections.Generic.List[int]
    $i = 0
    while ($i -lt $so.Length - $bytes.Length) {
        $match = $true
        for ($j=0; $j -lt $bytes.Length; $j++) {
            if ($so[$i+$j] -ne $bytes[$j]) {
                $match = $false
                break
            }
        }
        if ($match) { $hits.Add($i) }
        $i++
    }
    if ($hits.Count -gt 0) {
        Write-Output ("  {0,-10}  x{1,3}  first @ 0x{2:X}" -f $name, $hits.Count, $hits[0])
    }
}