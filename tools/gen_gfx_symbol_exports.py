"""Generate plain-name GL exports that forward to the __wrap_gl* wrappers.

Why this exists
---------------
Makefile passes -Wl,--wrap=<sym> for every GL/EGL symbol. That only rewrites
symbol resolution AT LINK TIME for the objects being linked. The guest is a
separate .so whose GL imports are bound by the dynamic linker through its GOT,
so on the Mesa path every one of the guest's GL calls lands in the real
libGLESv2 and never touches a counter. Measured on tag mesa3:

    backend=mesa frames=8640 draws=0/0 compile=0 link=0 prog=0 sh=0
    tex=0 texImg=0/0 compTex=0/0

vs the null backend, where the same guest produced draws=6/0 compile=92
link=46 prog=46 sh=92 tex=35 compTex=191 -- because there the null backend
intercepted eglGetProcAddress and handed back the wrappers by hand.

Note frames=8640 is the HOST frame loop (guest_view_probe.cpp:3857), not guest
drawing, so it says nothing either way about guest GL activity.

GL ONLY, no EGL. The first attempt exported both and wedged worse than any
previous run, dying at the process's very first EGL call
("view-egl-probe-begin", archive 20261011-1335*mesa4, threads=1,
total_imports=385). Exporting the real egl* names interposes on libEGL's OWN
internal calls, not just the guest's. EGL does not need this layer -- the probe
already logs every step of the ladder by name -- so only gl* is emitted.

Input : native-switch/source/gfx/gfx_gl_generated.inc
Output: native-switch/source/gfx/gfx_symbol_exports.inc
"""
import io
import os
import re
import sys

ROOT = r"E:\AI\RealRacing3-switch\native-switch\source\gfx"
GEN = os.path.join(ROOT, "gfx_gl_generated.inc")
OUT = os.path.join(ROOT, "gfx_symbol_exports.inc")

DECL = re.compile(
    r'extern\s+"C"\s+(?P<ret>[A-Za-z_][A-Za-z0-9_ :*]*?)\s+'
    r'__wrap_(?P<name>[A-Za-z0-9_]+)\s*\((?P<args>[^)]*)\)\s*;')

names = {}
with io.open(GEN, "r", encoding="utf-8", errors="replace") as fh:
    for line in fh:
        m = DECL.search(line)
        if m and m.group("name").startswith("gl"):
            names[m.group("name")] = (m.group("ret").strip(), m.group("args").strip())

def arg_names(arg_text):
    """'GLenum a0, GLsizei a1' -> 'a0, a1'; 'void' -> ''. A declaration is not an
    argument list: emitting the declaration text as the call arguments produces
    __wrap_f(GLenum a0, ...) and does not compile, and "(void)" must expand to an
    empty call, not to a literal "void" argument."""
    stripped = arg_text.strip()
    if stripped in ("", "void"):
        return ""
    out = []
    for part in stripped.split(","):
        part = part.strip()
        if not part:
            continue
        # The identifier is the last token: "const GLchar * a2" -> "a2".
        out.append(part.split()[-1].lstrip("*&"))
    return ", ".join(out)


lines = [
    "// GENERATED by tools/gen_gfx_symbol_exports.py -- do not edit by hand.",
    "// Plain-name forwarders so the dynamic linker binds the guest's GL/EGL",
    "// imports to this executable instead of to libGLESv2/libEGL directly.",
    "// -Wl,--wrap= cannot do this: it rewrites link-time references in the",
    "// objects being linked, and the guest is a separate .so resolved through",
    "// its GOT. Each forwarder simply calls the existing __wrap_ wrapper, so",
    "// behaviour is unchanged and only the accounting returns.",
    "// %d symbols." % len(names),
    "",
]

for name in sorted(names):
    ret, args = names[name]
    call = "__wrap_%s(%s)" % (name, arg_names(args))
    lines.append('extern "C" %s %s(%s) { return %s; }' % (ret, name, args, call))

lines.append("")

with io.open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines))

print("wrote %s with %d forwarders" % (OUT, len(names)))
for probe in ("glDrawArrays", "glDrawElements", "glCompileShader", "glLinkProgram",
              "eglSwapBuffers", "eglGetProcAddress"):
    print("  %-22s %s" % (probe, "present" if probe in names else "MISSING"))
